async function seedRealStudents() {
  console.log(`Starting migration with ${REAL_STUDENTS_DATA.length} verified CSE student records...`)

  // 1. Ensure CSE Department
  let dept = await prisma.department.findFirst({ where: { code: 'CSE' } })
  if (!dept) {
    dept = await prisma.department.create({
      data: { name: 'Computer Science and Engineering', code: 'CSE' },
    })
  }

  // 2. Fetch existing offerings for section A, B, C
  let offerings = await prisma.courseOffering.findMany({
    include: { subject: true },
  })

  // Ensure Section C offerings exist as well if only A and B exist
  const uniqueSubjects = await prisma.subject.findMany()
  const faculty = await prisma.faculty.findFirst()

  const sections = ['A', 'B', 'C']
  for (const sub of uniqueSubjects) {
    for (const sec of sections) {
      const exists = offerings.some((o) => o.subjectId === sub.id && o.section === sec)
      if (!exists && faculty) {
        const newOff = await prisma.courseOffering.create({
          data: {
            subjectId: sub.id,
            facultyId: faculty.id,
            academicYear: '2025-2026',
            semester: 5,
            section: sec,
          },
          include: { subject: true },
        })
        offerings.push(newOff)
      }
    }
  }

  console.log(`Course offerings ready across sections A, B, and C (${offerings.length} total).`)

  const allEnrollmentsToInsert: { studentId: string; courseOfferingId: string }[] = []
  let count = 0
  for (let i = 0; i < REAL_STUDENTS_DATA.length; i++) {
    const item = REAL_STUDENTS_DATA[i]
    count++

    // Determine section: 1-53 -> A, 54-106 -> B, 107-160 -> C
    let section = 'A'
    if (i >= 53 && i < 106) section = 'B'
    else if (i >= 106) section = 'C'

    const email = `${item.htNo.toLowerCase()}@edusync.edu`
    const batch = item.htNo.startsWith('23') ? '2023-2027' : '2024-2028'

    // Realistic attendance calculated from percentage & backlogs
    let attendance = Math.min(96, Math.max(62, Math.round(item.perc * 1.05)))
    if (item.backlogs > 2) attendance = Math.max(55, attendance - item.backlogs * 4)

    // Risk calculation
    let riskLevel = 'LOW'
    let riskScore = Math.max(8, Math.round((10 - item.cgpa) * 6))
    if (item.backlogs >= 3) {
      riskLevel = 'CRITICAL'
      riskScore = Math.min(95, 50 + item.backlogs * 5)
    } else if (item.backlogs >= 1) {
      riskLevel = 'MEDIUM'
      riskScore = 35 + item.backlogs * 10
    }

    // Deterministic 7-digit faceId
    const faceId = (1000000 + i * 3791 + parseInt(item.htNo.slice(-3).replace(/\D/g, '0') || '100')).toString()

    // Create or Upsert User
    const user = await prisma.user.upsert({
      where: { email },
      create: {
        email,
        name: item.name,
        role: 'STUDENT',
        avatar: `https://api.dicebear.com/7.x/initials/svg?seed=${encodeURIComponent(item.name)}`,
      },
      update: {
        name: item.name,
        role: 'STUDENT',
      },
    })

    // Create or Upsert Student
    const student = await prisma.student.upsert({
      where: { rollNo: item.htNo },
      create: {
        userId: user.id,
        rollNo: item.htNo,
        registerNo: item.htNo,
        batch,
        section,
        currentSemester: 5,
        departmentId: dept.id,
        currentCgpa: item.cgpa,
        attendancePercentage: attendance,
        riskLevel,
        riskScore,
        faceId,
        address: item.address || 'Andhra Pradesh, India',
        advisorNotes: `Admission Category: ${item.admissionType} | Active Backlogs: ${item.backlogs} | Cumulative Credits: ${item.credits}`,
      },
      update: {
        userId: user.id,
        name: undefined,
        batch,
        section,
        currentCgpa: item.cgpa,
        attendancePercentage: attendance,
        riskLevel,
        riskScore,
        address: item.address || undefined,
        advisorNotes: `Admission Category: ${item.admissionType} | Active Backlogs: ${item.backlogs} | Cumulative Credits: ${item.credits}`,
      } as any,
    })

    // Fee Setup (Base 55,000 INR rule)
    let totalFee = 55000
    let tuitionFee = 55000
    let labFee = 0
    let libraryFee = 0
    let examFee = 0
    let paidAmount = 55000
    let dueAmount = 0
    let feeStatus = 'PAID'

    if (item.admissionType === 'NRI') {
      totalFee = 75000
      labFee = 12000
      libraryFee = 4000
      examFee = 4000
      paidAmount = item.backlogs > 4 ? 40000 : 75000
      dueAmount = totalFee - paidAmount
      feeStatus = dueAmount === 0 ? 'PAID' : 'PARTIAL'
    } else if (item.admissionType === 'PIO') {
      totalFee = 65000
      labFee = 6000
      libraryFee = 2000
      examFee = 2000
      paidAmount = 65000
      dueAmount = 0
      feeStatus = 'PAID'
    } else {
      // CONVENOR / SPOT
      if (i % 7 === 0) {
        paidAmount = 35000
        dueAmount = 20000
        feeStatus = 'PARTIAL'
      } else if (i % 13 === 0) {
        paidAmount = 0
        dueAmount = 55000
        feeStatus = 'DUE'
      }
    }

    const paymentRef = `BVC-FEE-2025-${item.htNo}`
    await prisma.studentFee.upsert({
      where: { studentId: student.id },
      create: {
        studentId: student.id,
        academicYear: '2025-2026',
        totalFee,
        tuitionFee,
        specialLabFee: labFee,
        libraryFee,
        examFee,
        paidAmount,
        dueAmount,
        status: feeStatus,
        dueDate: new Date('2026-04-30'),
        lastPaymentDate: paidAmount > 0 ? new Date('2026-01-10') : null,
        paymentReference: paymentRef,
        paymentMode: paidAmount > 0 ? 'ONLINE_UPI' : 'PENDING',
      },
      update: {
        totalFee,
        tuitionFee,
        specialLabFee: labFee,
        libraryFee,
        examFee,
        paidAmount,
        dueAmount,
        status: feeStatus,
        dueDate: new Date('2026-04-30'),
        paymentReference: paymentRef,
      },
    })

    // Collect enrollments to bulk insert
    const sectionOfferings = offerings.filter((o) => o.section === section)
    for (const off of sectionOfferings) {
      allEnrollmentsToInsert.push({
        studentId: student.id,
        courseOfferingId: off.id,
      })
    }

    if (count % 25 === 0 || count === REAL_STUDENTS_DATA.length) {
      console.log(`  ✓ Synced ${count}/${REAL_STUDENTS_DATA.length} students (Latest: ${item.htNo} - ${item.name})`)
    }
  }

  console.log(`📦 Bulk inserting ${allEnrollmentsToInsert.length} course enrollments...`)
  await prisma.studentEnrollment.createMany({
    data: allEnrollmentsToInsert,
    skipDuplicates: true,
  })
  console.log(`✓ All enrollments successfully inserted.`)

  console.log(`\n🎉 All ${REAL_STUDENTS_DATA.length} CSE students successfully seeded into database!`)
}

seedRealStudents()
  .catch((e) => {
    console.error('Migration failed:', e)
    process.exit(1)
  })
  .finally(async () => {
    await prisma.$disconnect()
  })
